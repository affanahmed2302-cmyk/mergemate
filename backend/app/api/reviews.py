from __future__ import annotations
from fastapi import APIRouter, BackgroundTasks
from fastapi.responses import PlainTextResponse
from app.core.exceptions import NotFoundError, ValidationError
from app.core.store import store
from app.schemas.reviews import ReviewCreate, ReviewResponse
from app.services.review_service import run_review

router = APIRouter(prefix="/api/v1", tags=["reviews"])


@router.post("/reviews", response_model=ReviewResponse)
async def create_review(body: ReviewCreate, background_tasks: BackgroundTasks):
    if not body.pr_url or not body.pr_url.strip():
        raise ValidationError("pr_url is required")
    # Run synchronously for reliable demo (small PRs / demo mode)
    return await run_review(body.pr_url.strip(), demo=body.demo)


@router.get("/reviews", response_model=list[ReviewResponse])
async def list_reviews():
    return list(store._reviews.values())


@router.get("/reviews/{review_id}", response_model=ReviewResponse)
async def get_review(review_id: str):
    review = store.get(review_id)
    if not review:
        raise NotFoundError(f"Review {review_id} not found")
    return review


@router.get("/reviews/{review_id}/report.md")
async def report_markdown(review_id: str):
    review = store.get(review_id)
    if not review:
        raise NotFoundError(f"Review {review_id} not found")
    lines = [
        f"# MergeMate Review Report",
        f"",
        f"**Review ID:** {review.id}",
        f"**PR:** {review.pr_url}",
        f"**Status:** {review.status.value}",
        f"**Demo:** {review.is_demo}",
        f"",
    ]
    if review.executive_summary:
        lines += ["## Executive summary", "", review.executive_summary, ""]
    if review.scorecard:
        sc = review.scorecard
        lines += [
            "## Intelligence Scorecard",
            f"- Evidence coverage: {sc.evidence_coverage:.0%}",
            f"- Static-supported: {sc.static_supported}/{sc.total_findings}",
            f"- Unverified (AI): {sc.ai_unverified}",
            f"- Needs human review: {sc.needs_human_review}",
            f"- _{sc.disclaimer}_",
            "",
        ]
    if review.risk:
        lines += [
            "## Risk",
            f"- Score: {review.risk.score} ({review.risk.level})",
            f"- Formula: `{review.risk.formula}`",
            f"- _{review.risk.disclaimer}_",
            "",
        ]
    lines.append("## Findings")
    for f in review.findings:
        lines += [
            f"",
            f"### {f.title}",
            f"- Severity: {f.severity.value}",
            f"- Source: {f.source.value}",
            f"- Verification: **{f.verification_status.value}**",
            f"- File: `{f.file_path or 'n/a'}`",
            f"- Evidence: `{f.evidence.excerpt or 'none'}`",
            f"- {f.explanation}",
        ]
        if f.proof_steps:
            lines.append("- ProofLayer chain:")
            for s in f.proof_steps:
                lines.append(f"  {s.step}. {s.name} — {s.status}: {s.detail}")
    lines += ["", "---", "_Generated by MergeMate — evidence-first PR intelligence_"]
    return PlainTextResponse("\n".join(lines), media_type="text/markdown")


@router.post("/reviews/{review_id}/findings/{finding_id}/feedback")
async def finding_feedback(review_id: str, finding_id: str, body: dict):
    review = store.get(review_id)
    if not review:
        raise NotFoundError(f"Review {review_id} not found")
    fb = (body or {}).get("feedback")
    if fb not in {"useful", "incorrect", "disputed"}:
        raise ValidationError("feedback must be one of: useful, incorrect, disputed")
    for f in review.findings:
        if f.id == finding_id:
            f.feedback = fb
            store.update(review)
            return {"ok": True, "finding_id": finding_id, "feedback": fb}
    raise NotFoundError(f"Finding {finding_id} not found")
